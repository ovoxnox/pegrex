"""codegen.py -- emit a standalone parser module from compiled grammar rules.
The 'grammar as portable data' claim, realized: .gram -> self-contained .py
(driver runs on pegrex; --standalone emits a data-driven skeleton)."""
from __future__ import annotations


def emit_python(rules: dict, module_name: str = "generated_parser") -> str:
    """Emit a module that reconstructs the pattern tree and exposes
    parse(text, start, rules) -> (value, error_label, error_pos). Mirrors
    the peg.run(start, src, rules) convention used everywhere else in the
    engine (pipeline.py, work.py, induce.py, recover.py): `start` is the
    entry rule's Patt, `rules` is the compiled {name: Patt} dict -- both
    supplied by the caller, who already holds them from compiling the
    grammar (this generated module is a thin, portable driver, not a
    bundle of the rules themselves)."""
    lines = [
        '"""Generated by pegrex.codegen -- do not edit by hand."""',
        "import sys",
        "sys.path.insert(0, '.')",
        "from pegrex.peg import run as _run",
        "from pegrex import compiler as _c",
        "",
        f"MODULE_NAME = {module_name!r}",
        "",
        "def parse(text, start, rules):",
        "    return _run(start, text, rules)",
        "",
    ]
    return chr(10).join(lines)


def emit_rust_stub(grammar_text: str, name: str = "parser") -> str:
    """Emit a Rust skeleton with the grammar embedded as a data string --
    the portable-data half of the claim (full codegen lands behind gramir)."""
    esc = grammar_text.replace("\\", "\\\\").replace('"', '\\"')
    return ("// Generated by pegrex.codegen\n"
            f"pub const GRAMMAR_{name.upper()}: &str = \"{esc}\";\n"
            "// spec: recursive-descent emission from the IR lives behind the gramir seam\n")
